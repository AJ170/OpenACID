		public static bool IsStateContainedInArray(AnimatorStateMachineStatic.State _state, AnimatorStateMachineStatic.StateHashValue[] _states)
		{
			bool flag = false;
			for (int i = 0; i < _states.Length; i++)
			{
				if (flag)
				{
					break;
				}
				flag = _state.CompareNameHash(_states[i]);
			}
			return flag;
		}

		public static bool IsStateContainedInArray(int _stateHash, AnimatorStateMachineStatic.StateHashValue[] _states)
		{
			bool flag = false;
			for (int i = 0; i < _states.Length; i++)
			{
				if (flag)
				{
					break;
				}
				flag = _states[i].NameHash == _stateHash;
			}
			return flag;
		}
